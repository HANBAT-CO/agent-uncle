// Extract all ListRow.Texts variants from the pinned runtime AST, not a
// hand-maintained approximation of the documentation's examples.
import ts from 'typescript';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const source = await readFile(resolve(root, 'tool/tds_source/node_modules/@toss/tds-mobile/dist/esm/index.js'), 'utf8');
const file = ts.createSourceFile('tds.js', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
let cases;
function walk(n) {
  if (ts.isVariableDeclaration(n) && n.name.getText(file) === 'yD') {
    function findSwitch(node) {
      if (ts.isSwitchStatement(node)) cases = node.caseBlock.clauses;
      else ts.forEachChild(node, findSwitch);
    }
    findSwitch(n.initializer);
  }
  ts.forEachChild(n, walk);
}
walk(file);
if (!cases?.length) throw new Error('Missing ListRow.Texts runtime cases');
const props = n => Object.fromEntries(n.properties.filter(ts.isPropertyAssignment).map(p => [p.name.getText(file), p.initializer]));
function textStyle(p) {
  if (!ts.isStringLiteral(p.typography) || !ts.isStringLiteral(p.fontWeight) || !ts.isPropertyAccessExpression(p.color)) throw new Error('Unexpected text style');
  return { typography: p.typography.text, fontWeight: p.fontWeight.text, color: p.color.name.text };
}
const presets = Object.fromEntries(cases.map(c => {
  const ret = c.statements.find(ts.isReturnStatement);
  const p = props(ret.expression.arguments[1]);
  return [c.expression.text, p.typography ? [textStyle(p)] : ['topProps','middleProps','bottomProps'].filter(k => p[k]).map(k => textStyle(props(p[k])))];
}));
if (Object.keys(presets).length !== 25) throw new Error('Unexpected variant count');
const id = name => name.replace(/^Right/, 'right').replace(/^(\d)Row/, 'row$1');
let dart = `// GENERATED by tool/tds_source/lists.mjs from @toss/tds-mobile 2.5.1.\nimport '../foundation/theme.dart';\n\nenum TdsListRowTextType {\n`;
dart += Object.keys(presets).map(n => `  ${id(n)}('${n}')`).join(',\n') + `;\n  const TdsListRowTextType(this.sourceName);\n  final String sourceName;\n}\n\nconst tdsListRowTextPresets = <TdsListRowTextType, List<(TdsTypography, TdsFontWeight, String)>>{\n`;
for (const [name, rows] of Object.entries(presets)) dart += `  TdsListRowTextType.${id(name)}: [${rows.map(s => `(TdsTypography.${s.typography}, TdsFontWeight.${s.fontWeight}, '${s.color}')`).join(', ')}],\n`;
dart += '};\n';
await writeFile(resolve(root, 'packages/tds_mobile_flutter/lib/src/components/list_presets.g.dart'), dart);
await writeFile(resolve(root, 'packages/tds_mobile_flutter/reference/list-presets.json'), JSON.stringify(presets, null, 2)+'\n');
console.log(`Generated ${Object.keys(presets).length} ListRow.Texts presets from runtime.`);
