// Audited field-by-field by asset_frames_test.dart. Explicit descendants, never
// inherited status: a newly introduced source member still fails the inventory
// or geometry tests rather than silently appearing implemented.
function frameMembers(prefix, object) {
  return [prefix, ...Object.entries(object).flatMap(([key, v]) => {
    if (!['width','height','radius','acc','overlap','x','y','blur','spread'].includes(key)) {
      throw new Error(`Unaudited frame field: ${prefix}.${key}`);
    }
    return typeof v === 'object' ? frameMembers(`${prefix}.${key}`, v) : [`${prefix}.${key}`];
  })];
}
