String serviceCityPath(String region, String city) =>
    region == city ? region : '$region $city';

final serviceAreaPaths = <String>{
  for (final region in serviceRegions.entries) ...[
    region.key,
    for (final city in region.value.entries) ...[
      serviceCityPath(region.key, city.key),
      for (final district in city.value)
        '${serviceCityPath(region.key, city.key)} $district',
    ],
  ],
};

/// 과거의 자유 입력 지역도 선택 화면에서 확인·삭제할 때까지 보존한다.
Set<String> parseServiceAreas(String value) => value
    .split(' · ')
    .map((area) => area.trim())
    .where((area) => area.isNotEmpty)
    .toSet();

/// 전체와 하위 지역이 함께 저장되지 않게 한다. 다른 시·도의 선택은 유지한다.
Set<String> toggleServiceArea(Iterable<String> selected, String area) {
  final next = selected.toSet();
  if (next.remove(area)) return next;
  if (!serviceAreaPaths.contains(area)) return next;
  next.removeWhere(
    (other) =>
        serviceAreaPaths.contains(other) &&
        (other.startsWith('$area ') || area.startsWith('$other ')),
  );
  return next..add(area);
}
